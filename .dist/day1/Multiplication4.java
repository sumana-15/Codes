public class Multiplication4 {

    static int solve(int a, int b) {
        return a * b;
    }

    public static void main(String[] args) {
        int a = 5;
        int b = 10;

        int result = solve(a, b);
        System.out.println(result);
        System.out.println(result);
        System.out.println(result);
        System.out.println(result);
        System.out.println(result);


    }
}
